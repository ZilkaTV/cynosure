// Russian, Italian, Spanish and Korean cover the navigation, the shared UI pieces, the overview, the clan list and the
// points planner. Anything not listed here falls back to the English text (see translations.ts), so a missing key
// never shows up blank.
export type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends (...args: infer A) => infer R
    ? (...args: A) => R
    : T[K] extends object
      ? DeepPartial<T[K]>
      : T[K]
}

